// Local mock backend for the flattened source views.
// - GET /AMB/AMA04.html etc. serve the static views
// - POST /<app>/<view>/<route> accepts the form, then redirects to a
//   plausible next view (configurable below). This stands in for Java.
import { createServer } from 'node:http';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), 'mock-src');
const port = Number(process.argv[2] || 10083);

function buildAppOfView() {
  const map = {};
  for (const app of ["AMB", "AMC00", "ANB00"]) {
    const dir = join(root, app);
    if (!existsSync(dir)) continue;
    for (const f of readdirSync(dir)) {
      if (f.endsWith(".html")) map[f.replace(/\.html$/, "")] = app;
    }
  }
  return map;
}
const APP_OF_VIEW = buildAppOfView();

// route -> which view to render after the POST.
// Business-flow map lives in mock-routes.json (generated by exhaustive scan
// of formaction= in mock-src views); unknown routes fall back to re-rendering
// the same view, preserving the old inline-table behavior.
const NEXT = (() => {
  try {
    const spec = JSON.parse(readFileSync(join(root, '..', 'mock-routes.json'), 'utf8'));
    return Object.fromEntries(
      Object.entries(spec.routes || {}).map(([k, v]) => {
        // next is an app-absolute path like "/AMB/AMA03.html"; keep only the file
        const file = v.next.split('/').pop();
        return [k, file];
      })
    );
  } catch (e) {
    console.warn(`mock-routes.json unavailable (${e.code || e.message}); all POSTs re-render same view`);
    return {};
  }
})();

createServer(async (req, res) => {
  const url = new URL(req.url, `http://127.0.0.1:${port}`);
  if (req.method === 'GET') {
    let p = url.pathname.replace(/^\/(AMB|AMC00|ANB00)/, '$1');
    // shared static assets: try the requested app first, then AMB
    if (url.pathname.startsWith('/static/')) {
      const appPrefix = url.pathname.replace(/^\/(AMB|AMC00|ANB00)\//, '');
      void appPrefix;
    }
    if (p.endsWith('/')) p += 'index.html';
    const candidates = [join(root, p)];
    if (url.pathname.startsWith('/static/')) {
      // Static assets are per-app (tks_common.js only exists under ANB00, etc.).
      // Prefer the referring app, then try every app before giving up.
      let refApp = null;
      try { refApp = (new URL(req.headers.referer || '')).pathname.match(/^\/(AMB|AMC00|ANB00)\//)?.[1] || null; } catch { /* no referer */ }
      for (const app of [refApp, 'AMB', 'AMC00', 'ANB00']) {
        if (app) candidates.push(join(root, app, url.pathname));
      }
    }
    const file = candidates.find((f) => existsSync(f));
    if (existsSync(file)) {
      const body = readFileSync(file);
      res.writeHead(200, { 'content-type': p.endsWith('.js') ? 'text/javascript' : p.endsWith('.css') ? 'text/css' : 'text/html; charset=utf-8' });
      res.end(body);
      return;
    }
    res.writeHead(404); res.end(`not found: ${p}`);
    return;
  }
  // Read the request body once up front (needed for redirects on multipart
  // posts and for search-route parameter injection).
  const reqBody = await new Promise((resolve) => {
    let d = '';
    req.on('data', (c) => (d += c));
    req.on('end', () => resolve(d));
    req.on('error', () => resolve(d));
    setTimeout(() => resolve(d), 1000);
  });
  // Bare view paths (/AMA01/...) come from form actions without the app
  // prefix; rewrite to /<app>/<view>/<route> using the app that owns the view.
  const bare = url.pathname.match(/^\/((?:AMA|AMC|ANA|HQUIT)\w*)\/(\w+)$/);
  if (bare && req.method !== 'POST') {
    const [, view, route] = bare;
    const app = APP_OF_VIEW[view] || 'AMB';
    res.writeHead(302, { location: `/${app}/${view}/${route}` });
    res.end();
    return;
  }
  // POST: form submissions -> redirect to the mapped next view
  const m = url.pathname.match(/^\/(AMB|AMC00|ANB00)\/([A-Z0-9]+)\/(\w+)$/);
  const bareM = url.pathname.match(/^\/((?:AMA|AMC|ANA)\w*)\/(\w+)$/);
  if (m || bareM) {
    const [, app, view, route] = m || [null, APP_OF_VIEW[bareM[1]] || 'AMB', bareM[1], bareM[2]];
    const next = NEXT[`${view}/${route}`] || `${view}.html`;
    // Search routes re-render the view with a synthetic result row so
    // table-driven flows (募集人検索 etc.) behave like the real backend.
    if (/Search|PrevPage|NextPage/i.test(route)) {
      const d = reqBody;
      const pick = (name) => { const mm = new RegExp(name + '=[^&]*').exec(decodeURIComponent(d).replace(/\+/g, ' ')); return mm ? mm[0].split('=').pop() : ''; };
      const section = pick('section_code_key') || 'AHE61';
      const agent = pick('agent_code_key') || '252H';
      let html = readFileSync(join(root, app, next), 'utf8');
      const tb = html.search(/<tbody[^>]*id="gyoumu_list"/);
      if (tb >= 0) {
        const close = html.indexOf('</tbody>', tb);
        // Shape follows AMA18.html: radio named selectNo indexes list[i].field_agent_id.
        const row = `<tr><td class="sticky_table_value"><input type="radio" name="selectNo" value="0"></td>` +
          `<td class="sticky_table_value">${section}</td><td class="sticky_table_value">${agent}</td>` +
          `<td class="sticky_table_value">3028004586</td><td class="sticky_table_value" title="TEST">TEST</td></tr>` +
          `<input type="hidden" name="list[0].field_agent_id" value="3028004586">` +
          `<input type="hidden" name="list[0].field_agent_name" value="TEST">`;
        html = html.slice(0, close) + row + html.slice(close);
      }
      res.writeHead(200, { 'content-type': 'text/html; charset=utf-8' });
      res.end(html);
      console.log(`search POST ${url.pathname} -> ${next} (+result row ${section}/${agent})`);
      return;
    }
    res.writeHead(303, { location: `/${app}/${next}` });
    res.end();
    console.log(`POST ${url.pathname} -> /${app}/${next}`);
    return;
  }
  res.writeHead(404); res.end('no route');
}).listen(port, () => console.log(`mock-src server on http://127.0.0.1:${port}`));

